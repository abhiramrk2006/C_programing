#include <stdio.h>

int main() {
    int age = 20;
    float marks = 85.5f;
    double pi = 3.14159;
    char grade = 'A';
    char name[] = "Nova";

    printf("Name: %s\n", name);
    printf("Age: %d\n", age);
    printf("Marks: %f\n", marks);
    printf("Pi: %lf\n", pi);
    printf("Grade: %c\n", grade);

    return 0;
}